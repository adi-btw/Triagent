"""Compare eval runs of different models side by side: quality, behaviour, speed, cost.

    python -m eval.compare_models RUN_DIR [RUN_DIR ...]      # each holds summary.json
    python -m eval.compare_models --mode agent RUN_A RUN_B

Each run is a normal ``python -m eval.run_eval`` run, with the same cases and prompts and
a different model (``GEMINI_MODEL``, or ``LLM_PROVIDER=openai_compat`` + ``OPENAI_MODEL``).
Writes ``eval/results/model-comparison.md``.

Comparability rules, checked and reported:

* Same cases file and corpus (sha256 in each run's metadata); a mismatch is flagged.
* **Claim support is only comparable with the same judge.** Each run's judge model is shown,
  and the row is marked when they differ, because a lenient judge makes its own model look
  better. Severity, abstention, validity and clarification are scored against labels with
  no judge involved, so they're always comparable.
* Latency depends on where the model runs (an API vs a laptop CPU), so it's shown with
  the provider. Tokens per case are comparable; dollar cost only if prices are given.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

OUT = Path("eval/results/model-comparison.md")


def load(run_dir: Path) -> dict[str, Any]:
    path = run_dir / "summary.json" if run_dir.is_dir() else run_dir
    return json.loads(path.read_text(encoding="utf-8"))


def _rate(cell: dict | None, *, ci: bool = False) -> str:
    if not cell or not cell.get("n"):
        return "n/a"
    out = f"{cell['value'] * 100:.0f}% ({cell['k']:.0f}/{cell['n']:.0f})"
    if ci and cell.get("ci"):
        out += f" [{cell['ci'][0] * 100:.0f}–{cell['ci'][1] * 100:.0f}]"
    return out


ROWS: list[tuple[str, Any]] = [
    ("Severity exact [95% CI]", lambda m: _rate(m["severity"]["exact"], ci=True)),
    ("Severity within one level", lambda m: _rate(m["severity"]["within_one"])),
    ("Correct abstention (7 uncovered)", lambda m: _rate(m["abstention"]["correct_abstention"])),
    ("False abstention (lower is better)", lambda m: _rate(m["abstention"]["false_abstention"])),
    ("Report accepted by validator", lambda m: _rate(m["validity"]["status"]["ok"])),
    ("Rejected (invalid_output)", lambda m: _rate(m["validity"]["status"]["invalid_output"])),
    ("Crashed / provider error", lambda m: _rate(m["validity"]["status"]["error"])),
    ("Clarifying question on vague cases (agent)",
     lambda m: _rate(m["clarification"]["clarification_rate"])),
    ("Claims supported (judge)", lambda m: _rate(m["claim_support"]["supported"], ci=True)
     if (m.get("claim_support") or {}).get("claims") else "not judged"),
    ("Latency p50 / p95", lambda m: f"{m['latency']['p50_ms'] / 1000:.1f}s / "
     f"{m['latency']['p95_ms'] / 1000:.1f}s" if m["latency"].get("p50_ms") else "n/a"),
    ("LLM calls / tokens per case", lambda m: f"{m['latency']['mean_llm_calls']:.1f} / "
     f"{m['latency']['mean_tokens']:,.0f}" if m["latency"].get("mean_tokens") else "n/a"),
]


def render(runs: list[dict[str, Any]], mode: str) -> str:
    metas = [r["metadata"] for r in runs]
    names = [f"{m['llm_model']}" for m in metas]
    lines = [f"# Model comparison ({mode} mode)", "",
             "Generated by `python -m eval.compare_models`. Same 32 labelled cases, prompts and "
             "retrieval for every model; only the model changes.", ""]
    warn = []
    if len({m.get("cases_sha256") for m in metas}) > 1:
        warn.append("**The runs used different case files: not comparable.**")
    if len({m.get("corpus_sha256") for m in metas}) > 1:
        warn.append("**The runs used different corpora: not comparable.**")
    for m in metas:
        hits = str(m.get("llm_cache_hits") or "0/0").split("/")[0]
        if hits.isdigit() and int(hits) > 0:
            warn.append(f"`{m['llm_model']}`: {m['llm_cache_hits']} LLM calls were replayed "
                        "from the cache, so its latency row understates model time.")
    judges = {m.get("judge_model") for m in metas if m.get("judge_enabled")}
    if len(judges) > 1:
        warn.append("Claim support was graded by different judges "
                    f"({', '.join(sorted(map(str, judges)))}): compare that row with care.")
    lines += warn + ([""] if warn else [])
    lines += ["| | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    lines.append("| Provider | " + " | ".join(m.get("llm_provider", "?") for m in metas) + " |")
    lines.append("| Judge | " + " | ".join(
        str(m.get("judge_model")) if m.get("judge_enabled") else "none" for m in metas) + " |")
    for label, fn in ROWS:
        cells = []
        for r in runs:
            m = r["metrics"]["by_mode"].get(mode)
            if not m:
                cells.append("mode not run")
                continue
            try:
                cells.append(fn(m))
            except (KeyError, TypeError, AttributeError):  # metric not defined here
                cells.append("n/a")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += ["", "Run ids: " + ", ".join(f"`{m['run_id']}`" for m in metas), ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m eval.compare_models")
    p.add_argument("runs", nargs="+", type=Path, help="run dirs or summary.json files")
    p.add_argument("--mode", default="rag", choices=["no_retrieval", "rag", "agent"])
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args(argv)
    runs = [load(r) for r in args.runs]
    args.out.write_text(render(runs, args.mode), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
