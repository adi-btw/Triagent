"""Close the loop: reviewer feedback -> a report, and -> candidate eval cases.

    python -m eval.feedback report         # eval/results/feedback-latest.md
    python -m eval.feedback export-cases   # data/eval/feedback_candidates.jsonl

Feedback comes from ``POST /feedback`` (the demo UI's "Was this triage right?"). It is
stored in ``FEEDBACK_DB_PATH`` next to the exact triage it rates (app/feedback.py).

**report** answers the questions that decide what to fix next. What share of triages
reviewers accept, by mode, model and prompt version. Where severity was wrong, and in
which direction. Which incidents should have been abstentions. Which chunks reviewers
flag as not supporting their claim (a retrieval or corpus problem, not a model one).

**export-cases** turns reviewed triages into labelled cases in the ``cases.jsonl``
format, validated by ``EvalCase``:

* thumbs-up on an accepted report: the report's own severity and citations become the
  labels. It's a regression case for behaviour a reviewer confirmed.
* thumbs-down with a correction: the corrected severity and/or ``should_abstain``,
  with the reviewer's flagged citations removed from the expected chunks.
* thumbs-down with no correction says something is wrong but not what, so there's no
  label. These are counted as "needs labelling" and not exported.

Candidates go to a separate file for a person to review before they're appended to
``cases.jsonl``. Labels learned from one reviewer's clicks shouldn't enter the eval set
unread. Incidents already in the eval set are skipped, matched on normalised text.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from pydantic import ValidationError

from app.config import Settings
from app.feedback import FeedbackStore
from eval.cases import DEFAULT_CASES_PATH, EvalCase

REPORT = Path("eval/results/feedback-latest.md")
CANDIDATES = Path("data/eval/feedback_candidates.jsonl")
SEV_ORDER = {"SEV1": 1, "SEV2": 2, "SEV3": 3, "SEV4": 4}


def _norm(text: str) -> str:
    return " ".join(text.lower().split())


def _pct(k: int, n: int) -> str:
    return f"{k / n * 100:.0f}% ({k}/{n})" if n else "n/a"


# --------------------------------------------------------------------------- report


def summarize(rows: list[dict[str, Any]]) -> dict[str, Any]:
    by: dict[str, dict[str, list[int]]] = {"mode": defaultdict(list), "model": defaultdict(list),
                                           "prompt": defaultdict(list)}
    sev_pairs: Counter[tuple[str, str]] = Counter()
    missed_abstain, wrong_abstain, flagged = [], [], Counter()
    for r in rows:
        up = int(r["rating"] == "up")
        by["mode"][r["mode"]].append(up)
        by["model"][r["model"]].append(up)
        for p in r["prompt_versions"] or ["(none)"]:
            by["prompt"][p].append(up)
        if r["correct_severity"] and r["correct_severity"] != r["severity"]:
            sev_pairs[(r["severity"] or "none", r["correct_severity"])] += 1
        if r["should_abstain"] and not r["abstained"]:
            missed_abstain.append(r)
        if r["should_abstain"] is False and r["abstained"]:
            wrong_abstain.append(r)
        flagged.update(r["wrong_citations"])
    under = sum(n for (got, want), n in sev_pairs.items()
                if got in SEV_ORDER and SEV_ORDER[want] < SEV_ORDER[got])
    over = sum(n for (got, want), n in sev_pairs.items()
               if got in SEV_ORDER and SEV_ORDER[want] > SEV_ORDER[got])
    return {"n": len(rows), "up": sum(r["rating"] == "up" for r in rows), "by": by,
            "sev_pairs": sev_pairs, "under_rated": under, "over_rated": over,
            "missed_abstain": missed_abstain, "wrong_abstain": wrong_abstain,
            "flagged": flagged, "needs_labelling": sum(1 for r in rows if _unlabelled(r))}


def _unlabelled(r: dict[str, Any]) -> bool:
    return (r["rating"] == "down" and not r["correct_severity"]
            and r["should_abstain"] is None)


def render(s: dict[str, Any], counts: dict[str, int]) -> str:
    lines = ["# Reviewer feedback", "",
             f"Generated by `python -m eval.feedback report`. {counts['feedback']} of "
             f"{counts['triages']} recorded triages have reviewer feedback.", ""]
    if not s["n"]:
        return "\n".join(lines + ["_No feedback yet._", ""])
    lines += [f"**Accepted (thumbs up): {_pct(s['up'], s['n'])}.**", ""]
    for key, title in (("mode", "Mode"), ("model", "Model"), ("prompt", "Prompt version")):
        lines += [f"| {title} | Accepted |", "|---|---|"]
        for name, votes in sorted(s["by"][key].items()):
            lines.append(f"| {name} | {_pct(sum(votes), len(votes))} |")
        lines.append("")
    lines += ["## Severity corrections", ""]
    if s["sev_pairs"]:
        lines += [f"Reviewers rated the incident **more severe** than the report "
                  f"{s['under_rated']} time(s) (under-rated), **less severe** "
                  f"{s['over_rated']} time(s).", "",
                  "| Report said | Reviewer says | Count |", "|---|---|---|"]
        lines += [f"| {got} | {want} | {n} |" for (got, want), n in s["sev_pairs"].most_common()]
    else:
        lines.append("_None._")
    lines += ["", "## Abstention", "",
              f"- Should have abstained but answered: {len(s['missed_abstain'])}",
              f"- Abstained but reviewer says the runbooks cover it: {len(s['wrong_abstain'])}",
              "", "## Citations flagged as not supporting their claim", ""]
    if s["flagged"]:
        lines += ["| Chunk | Times flagged |", "|---|---|"]
        lines += [f"| `{c}` | {n} |" for c, n in s["flagged"].most_common(15)]
    else:
        lines.append("_None._")
    lines += ["", f"{s['needs_labelling']} thumbs-down without a correction need labelling "
              "before they can become eval cases.", ""]
    return "\n".join(lines)


# --------------------------------------------------------------------------- export


def to_case(r: dict[str, Any], case_id: str) -> dict[str, Any] | None:
    """A candidate ``EvalCase`` dict, or None when the feedback carries no label."""
    report = r["report"] or {}
    if r["rating"] == "up":
        if r["status"] != "ok":
            return None
        abstain = r["abstained"]
        severity = r["severity"]
    else:
        if _unlabelled(r):
            return None
        abstain = bool(r["should_abstain"]) if r["should_abstain"] is not None else r["abstained"]
        severity = r["correct_severity"] or (r["severity"] if r["status"] == "ok" else None)
    wrong = set(r["wrong_citations"])
    if abstain:  # an abstention still rates severity from the policy, as in cases.jsonl
        chunks = [c for c in report.get("severity_citations", []) if c not in wrong]
    else:
        chunks = [c for c in r["cited_ids"] if c not in wrong]
    category = ("insufficient_evidence" if abstain
                else "ambiguous" if r["clarification"] else "answerable")
    note = f"From reviewer feedback on triage {r['triage_id']} ({r['rating']}, {r['mode']} mode)"
    if r["comment"]:
        note += f": {r['comment']}"
    return {
        "id": case_id, "category": category, "incident": r["incident"],
        "expected_severity": severity,
        "expected_doc_ids": sorted({c.split("#", 1)[0] for c in chunks}),
        "expected_chunk_ids": sorted(chunks), "should_abstain": abstain,
        "clarification": r["clarification"] if category == "ambiguous" else None,
        "notes": note,
    }


def export_cases(rows: list[dict[str, Any]], existing: list[dict[str, Any]]
                 ) -> tuple[list[dict[str, Any]], dict[str, int]]:
    seen = {_norm(c["incident"]) for c in existing}
    next_id = 1 + max((int(c["id"].split("-")[1]) for c in existing), default=0)
    latest: dict[str, dict[str, Any]] = {}
    for r in rows:  # rows are ordered by feedback time: the last verdict wins
        latest[_norm(r["incident"])] = r
    out, stats = [], Counter()
    for key, r in latest.items():
        if key in seen:
            stats["already_in_eval_set"] += 1
            continue
        case = to_case(r, f"case-{next_id:03d}")
        if case is None:
            stats["no_label"] += 1
            continue
        try:
            EvalCase.model_validate(case)
        except ValidationError as exc:
            stats["invalid"] += 1
            print(f"skipped {r['triage_id']}: {exc.errors()[0]['msg']}", file=sys.stderr)
            continue
        out.append(case)
        next_id += 1
    stats["exported"] = len(out)
    return out, dict(stats)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m eval.feedback")
    p.add_argument("--db", type=Path, default=None, help="default: FEEDBACK_DB_PATH")
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("report")
    r.add_argument("--out", type=Path, default=REPORT)
    e = sub.add_parser("export-cases")
    e.add_argument("--out", type=Path, default=CANDIDATES)
    e.add_argument("--cases", type=Path, default=DEFAULT_CASES_PATH)
    args = p.parse_args(argv)
    db = args.db or Settings().feedback_db_path
    if not Path(db).exists():
        print(f"no feedback database at {db}", file=sys.stderr)
        return 1
    store = FeedbackStore(db)
    rows = store.rows()
    if args.cmd == "report":
        args.out.write_text(render(summarize(rows), store.counts()), encoding="utf-8",
                            newline="\n")
        print(f"{len(rows)} reviewed triages; wrote {args.out}")
        return 0
    existing = [json.loads(x) for x in args.cases.read_text(encoding="utf-8").splitlines()
                if x.strip()]
    cases, stats = export_cases(rows, existing)
    with args.out.open("w", encoding="utf-8", newline="\n") as f:
        for c in cases:
            f.write(json.dumps(c, ensure_ascii=False) + "\n")
    print(f"{stats}; wrote {args.out}. Review each case, then append the ones you accept "
          f"to {args.cases}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
